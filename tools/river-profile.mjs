/**
 * Turns the river asset's own waterline into the table the terrain is cut to.
 *
 * The Blender build writes river-profile.json beside the .blend: one row per
 * cross-section of the water body, with the half-width of each bank there. The
 * terrain reads it (riverProfile.ts) so the ground is shaped for exactly the
 * channel that is drawn in it — when the two disagreed, the outside of every bend
 * showed either dry bed or water lying above the grass.
 *
 * Run after exporting the river: node tools/river-profile.mjs
 */
import fs from 'node:fs'

const src = JSON.parse(fs.readFileSync('art/blender/river/river-profile.json', 'utf8'))
const stations = src.stations
const start = stations[0][0]
const step = (stations[stations.length - 1][0] - start) / (stations.length - 1)

const rows = stations.map(([, neg, pos]) => `  [${neg.toFixed(3)}, ${pos.toFixed(3)}],`).join('\n')
const out = `/**
 * GENERATED by tools/river-profile.mjs from art/blender/river/river-profile.json — do not edit.
 *
 * The river's waterline, one row per cross-section of the water body: the half-width
 * of the negative and the positive bank, in metres, measured from the centre-line.
 * Rows are evenly spaced along the run, starting ${start.toFixed(2)} m before the stream begins
 * and continuing past its end, because the channel runs off into the fog at both ends.
 */
export const RIVER_PROFILE_START = ${start.toFixed(3)}
export const RIVER_PROFILE_STEP = ${step.toFixed(5)}
export const RIVER_LENGTH = ${src.length}

export const RIVER_PROFILE: readonly (readonly [neg: number, pos: number])[] = [
${rows}
]
`
fs.writeFileSync('src/game/world/riverProfile.ts', out)
console.log(`${stations.length} stations, ${start.toFixed(2)}..${(start + step * (stations.length - 1)).toFixed(2)} m, step ${step.toFixed(3)} m`)
